#pragma once
// B3.2: ring mathematics for quadratic rings (certificate type 1). Pure functions: no engine
// state. Specification: docs/extension-certificates.md, docs/rings-design.md (R3, R4, R7-R10),
// docs/ring-records.md, docs/degree-sheets.md.
//
// Conventions: D is a fundamental discriminant; omega = (1 + sqrt D)/2 if D = 1 (mod 4), else
// sqrt(D/4); O_K = Z[omega]; elements are c0 + c1*omega with signed integers. The prime ideal
// labeled (q, r) is (q, omega - r), r a root of f mod q. A generator's root is not stored: it is
// derived as r = -c0/c1 (mod q).
#include "primechain_next/model.hpp"

#include <functional>
#include <optional>
#include <string>
#include <utility>
#include <vector>

namespace primechain::next {

constexpr std::uint64_t kQuadraticCertificateType = 1;

// "This integer is prime" as the chain knows it. The Engine (B3.4, Engine::chainPrime) answers
// exactly from chain data: on chain up to the frontier F, trial division by chain primes up to F^2.
using PrimeOracle = std::function<bool(const Integer&)>;

struct QuadElement {   // c0 + c1*omega, signed
    Integer c0;
    Integer c1;
    bool operator==(const QuadElement&) const = default;
};

struct QuadGenerator {  // a generator of the prime above q with the smaller (or double) root
    Integer q;
    QuadElement g;
    bool operator==(const QuadGenerator&) const = default;
};

struct QuadCertificate {
    std::uint64_t version{kVersion1};
    Integer d;                                              // the ring's identity
    std::vector<std::pair<Integer, std::uint64_t>> factors; // |D| = prod p^e, increasing p
    std::vector<QuadGenerator> generators;                  // every non-inert q <= M_K, increasing
    std::optional<QuadElement> unit;                        // required for D > 0, absent for D < 0
    bool operator==(const QuadCertificate&) const = default;
};

enum class RowType : std::uint8_t { Inert = 0, Split = 1, Ramified = 2 };  // 2 bits on the wire

struct Segment {  // one mined segment (R7), as signed by the miner
    std::uint64_t version{kVersion1};
    Hash256 ring_id{};
    Integer start;                     // first main-chain prime of the segment
    std::vector<RowType> rows;         // one per main-chain prime from `start`, in order
    std::vector<QuadElement> generators;  // one per paid row, in order
    bool operator==(const Segment&) const = default;
};

struct RingPrime {          // a new asset (ring number, q, i) with its ramification index
    std::uint64_t ring{0};
    Integer q;
    std::uint32_t i{0};     // 0 = smaller root (or the ramified prime), 1 = larger root
    std::uint32_t e{1};
    Integer root;           // label: the root of f mod q
};

struct CertificateLimits {  // parameters CertificateBytes, CertificateIntegerBytes, RingEligibilityExponent
    std::uint64_t certificate_bytes{256u << 10};
    std::uint64_t integer_bytes{4096};
    std::uint64_t eligibility_exponent{2};
};

struct SegmentLimits {      // parameters SegmentPaidRows, SegmentInertRows, GeneratorBytes
    std::uint64_t paid_rows{32};
    std::uint64_t inert_rows{1024};
    std::uint64_t generator_bytes{4096};  // [65] each coefficient of a recorded generator (B3.5)
};

// Hard decoder bound for generator coefficients in ring records (the voted limit is parameter
// GeneratorBytes, [65], whose upper bound this is).
constexpr std::size_t kMaxGeneratorBytes = 1u << 20;

// Arithmetic in Z[omega].
Integer quadNorm(const Integer& d, const QuadElement& a);
QuadElement quadMul(const Integer& d, const QuadElement& a, const QuadElement& b);
QuadElement quadConjugate(const Integer& d, const QuadElement& a);
Integer quadHeight(const QuadElement& a);  // c0^2 + c1^2
RowType rowType(const Integer& d, const Integer& q);  // by the Kronecker symbol (D/q)
bool isRoot(const Integer& d, const Integer& q, const Integer& r);
Integer otherRoot(const Integer& d, const Integer& q, const Integer& r);
// The root of the prime generated by g: r = -c0/c1 mod q; nullopt if c1 = 0 mod q.
std::optional<Integer> derivedRoot(const Integer& q, const QuadElement& g);
// R10 for D > 0: neither g*eps nor g/eps has a smaller height. Always true without a unit.
bool isReduced(const Integer& d, const QuadElement& g, const std::optional<QuadElement>& unit);

bool isFundamental(const Integer& d, const std::vector<std::pair<Integer, std::uint64_t>>& factors,
                   const PrimeOracle& is_prime, std::string& error);
bool eligible(const Integer& d, const Integer& frontier, std::uint64_t exponent);  // |D| <= F^t
// Minkowski: is M_K below x? (integers only; equality is impossible where it is used)
bool minkowskiBelow(const Integer& d, const Integer& x);

// R4: ring ID = hash(type || degree || identity).
Hash256 quadraticRingId(const Integer& d);

// Canonical encodings (versioned, strict, bounded). Signed integers: one sign byte (0 or 1, never
// 1 for zero), then the magnitude.
Bytes encode(const QuadCertificate& cert);
bool decode(const Bytes& data, QuadCertificate& out, const CertificateLimits& limits, std::string& error);
Bytes encode(const Segment& segment);
// max_integer_bytes bounds generator coefficients and the start prime.
bool decode(const Bytes& data, Segment& out, const SegmentLimits& limits, std::size_t max_integer_bytes,
            std::string& error);

// Full check of a certificate against the frontier F. `primes`: the chain's primes in order, at
// least up to the Minkowski bound (every prime <= M_K is <= F, R3).
bool verifyCertificate(const QuadCertificate& cert, const Integer& frontier, const std::vector<Integer>& primes,
                       const PrimeOracle& is_prime, const CertificateLimits& limits, std::string& error);

// Segment body inside a ring block: the row types and generators only (the ring and the start
// prime follow from the ring block). Same bytes as encode(Segment) after the start prime.
void encodeSegmentBody(Writer& w, const Segment& segment);
bool decodeSegmentBody(Reader& r, Segment& out, const SegmentLimits& limits, std::string& error);
// The last main-chain prime of a segment (its last row), given the primes from its start on.
Integer segmentLast(const Segment& segment, const std::vector<Integer>& primes);

// Full check of a segment of ring `ring_number` (identity d, unit from its certificate).
// `primes`: the main-chain primes from the segment's start on, in order, up to the frontier.
// On success, `out` holds the new ring primes in order.
bool checkSegment(const Integer& d, const std::optional<QuadElement>& unit, std::uint64_t ring_number,
                  const Segment& segment, const std::vector<Integer>& primes, const SegmentLimits& limits,
                  std::vector<RingPrime>& out, std::string& error);

// ---------------------------------------------------------------- B3.5: mining records
// docs/ring-records.md section 3, rings-design.md R7.

// RING_WORK (a message, journal data D15): 1 to SegmentsPerSignature consecutive complete segments
// of one ring, signed once by the miner. Each segment competes and is accepted on its own (D4).
struct RingWork {
    std::uint64_t version{kVersion1};
    std::string network_id;
    Hash256 ring_id{};
    Address miner;
    Bytes public_key;               // optional once the miner's key is registered
    Integer start;                  // the first segment's start
    std::vector<Segment> segments;  // each carries the ring ID and its own start
    Bytes signature;
    bool operator==(const RingWork&) const = default;
};

// Ring block (one per ring per batch): the ring, the previous ring block hash (the ring's tip), the
// start prime, then groups (miner, hash of the signed RING_WORK, its accepted segments).
struct RingGroup {
    Address miner;
    Hash256 work_hash{};
    std::vector<Segment> segments;  // in a ring block only rows and generators are written
    bool operator==(const RingGroup&) const = default;
};

struct RingBlock {
    std::uint64_t version{kVersion1};
    std::uint64_t ring{0};
    Hash256 previous{};
    Integer start;
    std::vector<RingGroup> groups;
    bool operator==(const RingBlock&) const = default;
};

// Ring batch, the third kind of consensus decision (B3.6, A3-1): open height h (the main block
// whose rows these are), the hash of main block h - 1, the ring blocks by increasing ring number,
// then the RING_REVEALs (ring-records section 3). Applied in that order: rows first, then the
// reveals, then the openings (R5) for h. At most parameter 35 bytes, reveals included.
struct RingBatch {
    std::uint64_t version{kVersion1};
    std::string network_id;
    std::uint64_t open_height{0};
    Hash256 previous_main{};
    std::vector<RingBlock> blocks;
    std::vector<RingReveal> reveals;
    bool operator==(const RingBatch&) const = default;
};

Bytes ringWorkSigningPayload(const RingWork& work);
Bytes encode(const RingWork& work);
bool decode(const Bytes& data, RingWork& out, std::size_t max_text, std::string& error);
Hash256 ringWorkHash(const RingWork& work);  // covers the signature (the "hash of the signed RING_WORK")
Bytes encode(const RingBlock& block);
Hash256 ringBlockHash(const RingBlock& block);  // the ring's new tip
Bytes encode(const RingBatch& batch);
// Ring IDs and starts of the segments are left empty: the engine fills them from the ring record.
bool decode(const Bytes& data, RingBatch& out, std::size_t max_text, std::string& error);
Hash256 ringBatchHash(const RingBatch& batch);

}  // namespace primechain::next
